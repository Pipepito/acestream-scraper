// Markdown is the source. Keep the supported subset deliberately small and safe:
// one version heading, one summary paragraph, section headings and bullets with optional GitHub links.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const fail = (message) => { throw new Error(message); };
function parseNotes(text, version) {
  const lines = text.trim().split(/\r?\n/).filter(line => line.trim());
  if (lines.shift() !== `# ${version}`) fail(`Invalid title for ${version}`);
  const summary = lines.shift();
  if (!summary || /^[#-]/.test(summary)) fail(`Missing summary for ${version}`);
  const sections = [];
  for (const line of lines) {
    if (line.startsWith('## ') && line.length > 3) {
      const title = line.slice(3);
      if (sections.some(s => s.title === title)) fail(`Duplicate section in ${version}`);
      sections.push({ title, items: [] });
    } else if (line.startsWith('- ') && line.length > 2 && sections.length) {
      sections[sections.length - 1].items.push(line.slice(2));
    } else fail(`Unsupported Markdown in ${version}: ${line}`);
  }
  if (!sections.length || sections.some(s => !s.items.length)) fail(`Empty section in ${version}`);
  // Only explicit HTTPS GitHub links are supported; HTML and other Markdown stay forbidden.
  for (const text of [summary, ...sections.flatMap(s => [s.title, ...s.items])]) {
    const plain = text.replace(/\[([^\[\]\n]+)\]\(https:\/\/github\.com\/[A-Za-z0-9_./-]+\)/g, '$1');
    if (/[<>`*\[\]]|(^|\W)_|_(\W|$)/.test(plain)) fail(`Use plain text or HTTPS GitHub links in ${version}: ${text}`);
  }
  return { version, summary, sections };
}
function generate() {
  const directory = path.join(root, 'changelog');
  const versions = fs.readdirSync(directory).map(name => {
    if (!/^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)\.md$/.test(name)) fail(`Invalid changelog filename: ${name}`);
    return name.slice(0, -3);
  }).sort((a, b) => {
    const left = a.slice(1).split('.').map(Number), right = b.slice(1).split('.').map(Number);
    return right[0] - left[0] || right[1] - left[1] || right[2] - left[2];
  });
  if (!versions.length) fail('No release notes');
  const versionFile = path.join(root, '../version.txt');
  if (fs.existsSync(versionFile) && fs.readFileSync(versionFile, 'utf8').trim() !== versions[0]) fail('Newest notes must match version.txt');
  const releases = versions.map(version => parseNotes(fs.readFileSync(path.join(directory, `${version}.md`), 'utf8'), version));
  return '// Generated by npm run changelog from frontend/changelog/*.md. Do not edit.\n'
    + 'export interface ReleaseNotes { version: string; summary: string; sections: Array<{ title: string; items: string[] }> }\n'
    + `export const releases: ReleaseNotes[] = ${JSON.stringify(releases, null, 2)};\n`
    + 'export const currentRelease = releases[0];\n';
}
if (require.main === module) {
  const output = path.join(root, 'src/data/changelog.ts');
  const content = generate();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content) fail('Changelog drift: run npm run changelog and commit the result');
  } else fs.writeFileSync(output, content);
}
module.exports = { parseNotes, generate };
