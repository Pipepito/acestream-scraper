import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src');
const readMessages = (name) => JSON.parse(fs.readFileSync(path.join(root, 'i18n/messages', name), 'utf8'));
const en = readMessages('ui-en.json');
const es = readMessages('ui-es.json');
const keys = new Set(['Language', 'English', 'Español', 'Your language could not be remembered in this browser.']);
for (const name of fs.readdirSync(path.join(root, 'recipes'))) {
  if (!/\.tsx?$/.test(name) || name === 'messages.generated.ts') continue;
  const source = ts.createSourceFile(name, fs.readFileSync(path.join(root, 'recipes', name), 'utf8'), ts.ScriptTarget.Latest, true);
  const visit = (node) => {
    if (ts.isStringLiteral(node)) {
      if (Object.hasOwn(en, node.text)) keys.add(node.text);
      for (const plural of ['zero', 'one', 'two', 'few', 'many', 'other']) {
        const key = `${node.text}_${plural}`;
        if (Object.hasOwn(en, key)) keys.add(key);
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
}
const select = (messages) => Object.fromEntries([...keys].sort().map(key => {
  if (!Object.hasOwn(messages, key)) throw new Error(`Recipe translation missing: ${key}`);
  return [key, messages[key]];
}));
const output = `// Generated by scripts/sync-recipe-messages.mjs. No installed-app imports.\nexport const recipeResources = ${JSON.stringify({ en: { ui: select(en) }, es: { ui: select(es) } }, null, 2)} as const;\n`;
const destination = path.join(root, 'recipes/messages.generated.ts');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== output) throw new Error('Recipe translations drifted; run npm run recipes:messages');
} else fs.writeFileSync(destination, output);
